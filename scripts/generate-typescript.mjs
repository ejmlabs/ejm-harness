import { readFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

if (process.argv.length !== 3) {
  throw new Error("Usage: node scripts/generate-typescript.mjs <protocol.schema.json>");
}

const schema = JSON.parse(await readFile(process.argv[2], "utf8"));
// Preserve the empty request object's existing Record<string, unknown> contract.
schema.$defs.EmptyParams.additionalProperties = true;
// A default without a type still permits every JSON value, including scalars.
schema.$defs.ToolOutput.properties.data.tsType = "unknown";

process.stdout.write(
  await compile(schema, "ProtocolSchema", {
    additionalProperties: false,
    unknownAny: true,
    unreachableDefinitions: true,
    format: false,
    bannerComment: "// Generated by scripts/generate-protocol.py. Do not edit.",
  }),
);
