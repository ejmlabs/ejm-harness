#!/usr/bin/env python3
"""Generate SDK wire types with maintained generators from the Rust schema."""

from __future__ import annotations

import argparse
import os
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED_HEADER = "# Generated by scripts/generate-protocol.py. Do not edit."


def python_tool(name: str) -> list[str]:
    """Use the project's locked development toolchain."""
    return ["uv", "run", "--project", str(ROOT / "sdk/python"), "--group", "dev", "--locked", name]


def output(command: list[str], source: str | None = None) -> str:
    """Keep tool diagnostics visible while collecting its generated source."""
    return subprocess.run(
        command, input=source, text=True, stdout=subprocess.PIPE, check=True, cwd=ROOT
    ).stdout


def python_source(schema_path: Path, output_path: Path) -> str:
    """Generate Python 3.11 TypedDicts without adding SDK runtime dependencies."""
    subprocess.run(
        [
            *python_tool("datamodel-codegen"),
            "--input",
            str(schema_path),
            "--input-file-type",
            "jsonschema",
            "--output",
            str(output_path),
            "--output-model-type",
            "typing.TypedDict",
            "--target-python-version",
            "3.11",
            "--strict-nullable",
            "--enum-field-as-literal",
            "all",
            "--use-type-alias",
            "--use-standard-collections",
            "--use-union-operator",
            "--no-use-closed-typed-dict",
            "--strict-refs",
            "--no-allow-remote-refs",
            "--disable-timestamp",
            "--custom-file-header",
            GENERATED_HEADER,
            "--naming-strategy",
            "numbered",
            "--formatters",
            "builtin",
            "--type-mappings",
            "integer+uint=integer",
            "integer+uint32=integer",
            "integer+uint64=integer",
        ],
        cwd=ROOT,
        check=True,
    )
    return output(
        [
            *python_tool("ruff"),
            "format",
            "--stdin-filename",
            str(ROOT / "sdk/python/ejm_harness/protocol.py"),
        ],
        output_path.read_text(encoding="utf-8"),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    prettier = ["node", str(ROOT / "node_modules/prettier/bin/prettier.cjs")]
    with tempfile.TemporaryDirectory(prefix="ejm-harness-schema-") as folder:
        schema_path = Path(folder) / "protocol.schema.json"
        subprocess.run(
            [
                "cargo",
                "run",
                "--quiet",
                "--locked",
                "-p",
                "ejm-harness-worker",
                "--bin",
                "ejm-harness-protocol-schema",
                "--",
                str(schema_path),
            ],
            cwd=ROOT,
            check=True,
            env={**os.environ, "CARGO_BUILD_JOBS": "2"},
        )
        typescript = output(
            ["node", str(ROOT / "scripts/generate-typescript.mjs"), str(schema_path)]
        )
        outputs = {
            ROOT / "sdk/protocol.schema.json": output(
                [*prettier, "--parser", "json"], schema_path.read_text(encoding="utf-8")
            ),
            ROOT / "sdk/typescript/src/protocol.ts": output(
                [*prettier, "--parser", "typescript"], typescript
            ),
            ROOT / "sdk/python/ejm_harness/protocol.py": python_source(
                schema_path, Path(folder) / "protocol.py"
            ),
        }
    for path, source in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != source:
                raise SystemExit(f"generated file is stale: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source, encoding="utf-8")
    print(
        "SDK wire types match Rust schema"
        if args.check
        else "Generated SDK wire types from Rust schema"
    )


if __name__ == "__main__":
    main()
