import { DatabaseSync } from "node:sqlite";
import { readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.js";

const options = authOptions(
  {
    REGISTRY_ORIGIN: "https://registry.example.invalid",
    BETTER_AUTH_SECRET: "schema-generation-only-not-a-deployment-secret",
    GITHUB_CLIENT_ID: "schema-generation",
    GITHUB_CLIENT_SECRET: "schema-generation",
  },
  new DatabaseSync(":memory:"),
);
const migrations = await getMigrations(options);
const sql = `-- Generated by Better Auth 1.7.10. Run npm run schema:auth.\n${await migrations.compileMigrations()}\n`;
const path = new URL("../migrations/0001_auth.sql", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== sql) throw new Error("Better Auth migration is stale");
} else {
  await writeFile(path, sql);
}
