"""Types and result helpers for named package exports."""

from collections.abc import Iterator
from typing import Any, Protocol

from .protocol import ToolOutput


class ExtensionContext(Protocol):
    """Runtime context with snake_case metadata selected by the export kind."""

    def __getitem__(self, key: str) -> Any: ...
    def __iter__(self) -> Iterator[str]: ...
    def __len__(self) -> int: ...
    def get(self, key: str, default: object = None) -> Any: ...
    def is_cancelled(self) -> bool: ...
    def raise_if_cancelled(self) -> None: ...
    async def progress(self, message: str) -> None: ...
    async def delta(self, value: str) -> None: ...
    def progress_sync(self, message: str) -> None: ...
    def delta_sync(self, value: str) -> None: ...


def tool_output(
    content: str,
    *,
    data: object = None,
    is_error: bool = False,
    artifact: str | None = None,
) -> ToolOutput:
    """Build a tool result; data must be JSON serializable."""
    return {"content": content, "data": data, "is_error": is_error, "artifact": artifact}
