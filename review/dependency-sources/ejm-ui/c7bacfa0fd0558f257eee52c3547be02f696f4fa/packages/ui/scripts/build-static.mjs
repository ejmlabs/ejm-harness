#!/usr/bin/env node
/** Compile the native HTML profile from the shared theme and canonical control recipes. */
import { readFile, stat, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { buttonVariants, fieldClass } from '../src/control-recipes.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { compile, optimize } = await import(pathToFileURL(require.resolve('@tailwindcss/node')).href);
const output = resolve(root, 'public/static.css');
const base = buttonVariants({ variant: null, size: null, density: null }).split(/\s+/);
const applicable = value => value.split(/\s+/).filter(value => value !== 'group').join(' ');
const difference = props => applicable(buttonVariants({ variant: null, size: null, density: null, ...props }).split(/\s+/).filter(value => !base.includes(value)).join(' '));
const rules = [
  `[data-ejm="button"] { @apply ${applicable(buttonVariants({ variant: null }))}; text-decoration: none; }`,
  `[data-ejm="button"]:not([data-variant]), [data-ejm="button"][data-variant="primary"] { @apply ${difference({ variant: 'primary' })}; }`,
  ...['secondary', 'ghost', 'link', 'danger'].map(variant => `[data-ejm="button"][data-variant="${variant}"] { @apply ${difference({ variant })}; ${variant === 'link' ? 'white-space: normal;' : ''} }`),
  ...['sm', 'lg', 'icon'].map(size => `[data-ejm="button"][data-size="${size}"] { @apply ${difference({ size })}; }`),
  `[data-ejm="button"][data-density="compact"] { @apply ${difference({ density: 'compact' })}; }`,
  '[data-ejm="button"][data-density="compact"][data-size="icon"] { @apply size-8 px-0; }',
  '[data-ejm="button"][data-variant="link"] { @apply px-0; }',
  '[data-ejm="button"][data-size="sm"], [data-ejm="button"][data-density="compact"] { @apply touch-target; }',
  `[data-ejm="field"] { @apply ${fieldClass}; }`,
  'input[data-ejm="field"], select[data-ejm="field"] { @apply min-h-11; }',
  'textarea[data-ejm="field"] { @apply min-h-28 resize-y py-2.5; }',
];
const source = (await readFile(resolve(root, 'src/static.css'), 'utf8')) + '\n@layer components {\n' + rules.join('\n') + '\n}\n';
const compiler = await compile(source, { base: resolve(root, 'src'), onDependency: () => {} });
const css = '/* Generated by @ejm/ui build:static. Do not edit. */\n' + optimize(compiler.build([]), { minify: true }).code + '\n';
const cssGzip = gzipSync(css, { level: 9 }).length;
const fonts = await Promise.all(['manrope-latin.woff2', 'ibm-plex-mono-500-latin.woff2'].map(file => stat(resolve(root, 'src/fonts', file))));
const fontBytes = fonts.reduce((total, file) => total + file.size, 0);
if (cssGzip > 14 * 1024) throw new Error(`Static CSS exceeds 14 KiB gzip: ${cssGzip} bytes`);
if (fontBytes > 70 * 1024) throw new Error(`Static fonts exceed 70 KiB: ${fontBytes} bytes`);
if (process.argv.includes('--check')) {
  let existing;
  try { existing = await readFile(output, 'utf8'); } catch { /* A missing artifact is drift. */ }
  if (existing !== css) throw new Error('Static CSS is stale. Run npm run build:static -w @ejm/ui.');
} else {
  await writeFile(output, css);
}
console.log(`static HTML profile: ${Buffer.byteLength(css)} bytes, ${cssGzip} bytes gzip; fonts ${fontBytes} bytes; ${process.argv.includes('--check') ? 'artifact current' : 'artifact written'}`);
