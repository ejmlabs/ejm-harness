#!/usr/bin/env node
// Generates every file that carries colors from theme.json, so no surface keeps its own copy:
//   generated/tailwind.css   Tailwind v4 theme: brand palette, semantic colors, the four bands, elevation (sites and apps)
//   generated/window.css     the ui roles and syntax colors as Tailwind colors, for product windows and editors on the web
//   generated/neutral.css    opt-in neutral scale for native product styles on the web
//   generated/theme.css      the ui roles as plain --ejm-ui-* variables (dark by default), for the IDE and other non-Tailwind apps
//   generated/monaco/*.json  Monaco editor themes
//   generated/terminal/*     iTerm, Warp, Alacritty, kitty, Ghostty and Windows Terminal color schemes
//   rust/ejm_theme.rs        the ratatui palette (ejm_tui.rs sits next to it, hand written)
// Usage: node scripts/build-ui.mjs [--check]
//   --check verifies the contrast gates (scripts/contrast.mjs) and that every generated file is current; it exits 1
//   and names each stale file.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { checkAll } from './contrast.mjs';
import { loadTheme, resolveBands, resolveThemes, rgb, tokensRoot } from './theme.mjs';
import { tailwindCss, windowCss, neutralCss } from './tailwind.mjs';

const root = tokensRoot;
const { theme, brand } = loadTheme();
const check = process.argv.includes('--check');
const resolved = resolveThemes(theme);

// 1. Contrast rules.
const problems = checkAll(theme, brand);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

// 2. Generated files.
const files = new Map();
const hash = hex => `#${hex.toLowerCase()}`;
const banner = (c = '//') => `${c} Generated by packages/tokens/scripts/build-ui.mjs from packages/tokens/theme.json. Do not edit by hand.`;

function cssVars(name) {
  const t = resolved[name];
  const lines = [];
  for (const [k, v] of Object.entries(t.roles)) lines.push(`  --ejm-ui-${k}: ${hash(v)};`);
  t.neutral.forEach((v, i) => lines.push(`  --ejm-ui-n${i}: ${hash(v)};`));
  t.hues.forEach((v, i) => lines.push(`  --ejm-ui-hue-${i + 1}: ${hash(v)};`));
  for (const [k, v] of Object.entries(t.syntax)) lines.push(`  --ejm-ui-syn-${k}: ${hash(v)};`);
  return `  color-scheme: ${name};\n${lines.join('\n')}`;
}
files.set('generated/theme.css', `/* ${banner('').trim()}
   Dark is the default. Set data-theme="light" or "dark" on the root or on any .ejm-ui container.
   Without data-theme on the root, the system preference decides. */
:root, :root[data-theme="dark"], .ejm-ui[data-theme="dark"] {
${cssVars('dark')}
}
:root[data-theme="light"], .ejm-ui[data-theme="light"] {
${cssVars('light')}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
${cssVars('light').replace(/^/gm, '  ')}
  }
}
`);
files.set('generated/neutral.css', neutralCss({ resolved, banner: banner('').trim() }));

// Rust module for ratatui apps.
// type and macro are reserved words in Rust.
const rustName = k => ({ type: 'ty', macro: 'mac' }[k] ?? k.replace(/-/g, '_'));
const rc = hex => { const [r, g, b] = rgb(hex); return `Color::Rgb(0x${r.toString(16).padStart(2, '0')}, 0x${g.toString(16).padStart(2, '0')}, 0x${b.toString(16).padStart(2, '0')})`; };
const palette = (name) => {
  const t = resolved[name];
  const roles = ['accent', 'dim', 'warning', 'error', 'success', 'primary', 'text', 'text-strong', 'text-muted', 'text-subtle', 'ground', 'panel', 'line', 'special', 'diff-add', 'diff-del'];
  return `pub const ${name.toUpperCase()}: Palette = Palette {\n${roles.map(k => `    ${rustName(k)}: ${rc(t.roles[k])},`).join('\n')}\n    hues: [${t.hues.map(rc).join(', ')}],\n    syntax: Syntax {\n${Object.entries(t.syntax).map(([k, v]) => `        ${rustName(k)}: ${rc(v)},`).join('\n')}\n    },\n};`;
};
files.set('rust/ejm_theme.rs', `${banner()}
//! ejmlabs terminal theme for ratatui apps. See TUI.md for how each role is used.
//!
//! Terminal apps do not paint a background. Use these colors for text on the user's own terminal
//! background, pick DARK or LIGHT from the terminal's appearance, and fall back to the 16 color
//! sets below, then to bold and plain text under NO_COLOR.

use ratatui::style::Color;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Syntax {
${Object.keys(resolved.dark.syntax).map(k => `    pub ${rustName(k)}: Color,`).join('\n')}
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Palette {
${['accent', 'dim', 'warning', 'error', 'success', 'primary', 'text', 'text_strong', 'text_muted', 'text_subtle', 'ground', 'panel', 'line', 'special', 'diff_add', 'diff_del'].map(k => `    pub ${k}: Color,`).join('\n')}
    pub hues: [Color; 6],
    pub syntax: Syntax,
}

${palette('dark')}

${palette('light')}

/// Named colors for 16 and 256 color terminals, where truecolor is unavailable.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Basic {
    pub accent: Color,
    pub dim: Color,
    pub warning: Color,
    pub error: Color,
    pub success: Color,
}
pub const BASIC_DARK: Basic = Basic { accent: Color::Cyan, dim: Color::DarkGray, warning: Color::Yellow, error: Color::Red, success: Color::Green };
pub const BASIC_LIGHT: Basic = Basic { accent: Color::Blue, dim: Color::DarkGray, warning: Color::Magenta, error: Color::Red, success: Color::Green };

/// Symbols. Use ASCII when the locale is not UTF-8 or the user asks for plain output.
#[derive(Clone, Copy, Debug)]
pub struct Glyphs {
    pub prompt: &'static str,
    pub running: &'static str,
    pub idle: &'static str,
    pub ok: &'static str,
    pub fail: &'static str,
    pub warn: &'static str,
    pub tool: &'static str,
    pub quote: &'static str,
    pub up: &'static str,
    pub separator: &'static str,
    pub ellipsis: &'static str,
    pub spinner: &'static [&'static str],
}
pub const UNICODE: Glyphs = Glyphs {
    prompt: "\\u{203a}", running: "\\u{25cf}", idle: "\\u{25cb}", ok: "\\u{2713}", fail: "\\u{2717}", warn: "!",
    tool: "\\u{25b8}", quote: "\\u{258f}", up: "\\u{2191}", separator: "\\u{b7}", ellipsis: "\\u{2026}",
    spinner: &["\\u{280b}", "\\u{2819}", "\\u{2839}", "\\u{2838}", "\\u{283c}", "\\u{2834}", "\\u{2826}", "\\u{2827}", "\\u{2807}", "\\u{280f}"],
};
pub const ASCII: Glyphs = Glyphs {
    prompt: ">", running: "*", idle: "o", ok: "+", fail: "x", warn: "!", tool: ">", quote: "|", up: "^", separator: "-", ellipsis: "...",
    spinner: &["|", "/", "-", "\\\\"],
};
`);

// Monaco themes.
const tokenMap = {
  comment: 'comment', keyword: 'keyword', string: 'string', number: 'number', 'type.identifier': 'type', type: 'type', class: 'type', struct: 'type', enum: 'type', interface: 'type',
  typeParameter: 'type-parameter', function: 'function', method: 'function', macro: 'macro', parameter: 'parameter', property: 'property', field: 'property',
  enumMember: 'constant', 'variable.readonly': 'constant', constant: 'constant', namespace: 'namespace', decorator: 'macro', regexp: 'macro', tag: 'keyword',
  'attribute.name': 'function', 'attribute.value': 'string', key: 'function', identifier: 'identifier', delimiter: 'delimiter', annotation: 'macro',
  'entity.name.function': 'function', 'support.function': 'function', 'entity.name.type': 'type', 'entity.name.class': 'type', 'support.type': 'type', storage: 'keyword',
  'constant.numeric': 'number', 'constant.language': 'keyword', 'constant.other': 'constant', 'variable.parameter': 'parameter', 'variable.other.property': 'property',
  'variable.other.constant': 'constant', 'entity.name.tag': 'keyword', 'entity.other.attribute-name': 'function', 'support.type.property-name': 'function',
  'string.quoted.double.json': 'string', 'markup.heading': 'function', 'markup.inline.raw': 'string', 'markup.fenced_code': 'string', 'markup.underline.link': 'function',
};
for (const name of ['dark', 'light']) {
  const t = resolved[name];
  const r = t.roles;
  const n = t.neutral;
  const rules = Object.entries(tokenMap).map(([token, role]) => ({ token, foreground: t.syntax[role] }));
  rules.push({ token: 'markup.heading', foreground: t.syntax.function, fontStyle: 'bold' }, { token: 'markup.bold', fontStyle: 'bold' }, { token: 'markup.italic', fontStyle: 'italic' });
  const colors = {
    'editor.background': r.editor, 'editor.foreground': r.text,
    'editorLineNumber.foreground': r['text-subtle'], 'editorLineNumber.activeForeground': r.text,
    'editor.lineHighlightBackground': r.raised, 'editor.selectionBackground': r.selection, 'editor.inactiveSelectionBackground': name === 'dark' ? n[7] : n[8],
    'editorCursor.foreground': r.accent, 'editorIndentGuide.background1': r.line, 'editorIndentGuide.activeBackground1': n[9],
    'editorWidget.background': r.raised, 'editorWidget.foreground': r.text, 'editorWidget.border': r['line-strong'],
    'editorHoverWidget.background': r.raised, 'editorHoverWidget.border': r['line-strong'],
    'editorSuggestWidget.background': r.raised, 'editorSuggestWidget.border': r['line-strong'], 'editorSuggestWidget.selectedBackground': r.hover,
    focusBorder: r.focus, 'editorGutter.background': r.editor, 'editorOverviewRuler.border': r.editor,
    'peekViewEditor.background': r.raised, 'peekViewResult.background': r.raised, 'peekViewTitle.background': r.overlay,
    'menu.background': r.overlay, 'menu.foreground': r.text, 'menu.border': r['line-strong'], 'menu.selectionBackground': r.hover, 'menu.selectionForeground': r['text-strong'],
    'menu.separatorBackground': r['line-strong'], 'list.hoverBackground': r.hover, 'list.hoverForeground': r['text-strong'],
    disabledForeground: r['text-subtle'], 'editorGhostText.foreground': r['text-subtle'],
    'editorError.foreground': r.error, 'editorWarning.foreground': r.warning, 'diffEditor.insertedTextBackground': `${r['diff-add-bg']}`, 'diffEditor.removedTextBackground': `${r['diff-del-bg']}`,
  };
  const out = { base: name === 'dark' ? 'vs-dark' : 'vs', inherit: true, rules: rules.map(x => ({ ...x, ...(x.foreground ? { foreground: x.foreground } : {}) })), colors: Object.fromEntries(Object.entries(colors).map(([k, v]) => [k, `#${v}`])) };
  files.set(`generated/monaco/ejmlabs-${name}.json`, `${JSON.stringify(out, null, 2)}\n`);
}

// Terminal color schemes.
const ansiOrder = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white'];
const termRoles = name => {
  const t = resolved[name];
  return { bg: t.roles.ground, fg: t.roles.text, cursor: t.roles.accent, cursorText: t.roles.ground, selBg: t.roles.selection, selFg: t.roles['text-strong'], accent: t.roles.accent, ansi: t.ansi };
};
const ansi16 = a => [...ansiOrder.map(k => a[k]), ...ansiOrder.map(k => a[`bright-${k}`])];
const wtKey = k => (k === 'magenta' ? 'purple' : k);
for (const name of ['dark', 'light']) {
  const s = termRoles(name);
  const list = ansi16(s.ansi);
  files.set(`generated/terminal/ejmlabs-${name}.alacritty.toml`, `${banner('#')}
[colors.primary]
background = "${hash(s.bg)}"
foreground = "${hash(s.fg)}"

[colors.cursor]
text = "${hash(s.cursorText)}"
cursor = "${hash(s.cursor)}"

[colors.selection]
text = "${hash(s.selFg)}"
background = "${hash(s.selBg)}"

[colors.normal]
${ansiOrder.map(k => `${k} = "${hash(s.ansi[k])}"`).join('\n')}

[colors.bright]
${ansiOrder.map(k => `${k} = "${hash(s.ansi[`bright-${k}`])}"`).join('\n')}
`);
  files.set(`generated/terminal/ejmlabs-${name}.kitty.conf`, `${banner('#')}
foreground ${hash(s.fg)}
background ${hash(s.bg)}
selection_foreground ${hash(s.selFg)}
selection_background ${hash(s.selBg)}
cursor ${hash(s.cursor)}
cursor_text_color ${hash(s.cursorText)}
url_color ${hash(s.accent)}
active_border_color ${hash(resolved[name].roles.primary)}
inactive_border_color ${hash(resolved[name].roles.line)}
${list.map((v, i) => `color${i} ${hash(v)}`).join('\n')}
`);
  files.set(`generated/terminal/ejmlabs-${name}.ghostty`, `${banner('#')}
background = ${s.bg.toLowerCase()}
foreground = ${s.fg.toLowerCase()}
cursor-color = ${s.cursor.toLowerCase()}
cursor-text = ${s.cursorText.toLowerCase()}
selection-background = ${s.selBg.toLowerCase()}
selection-foreground = ${s.selFg.toLowerCase()}
${list.map((v, i) => `palette = ${i}=${hash(v)}`).join('\n')}
`);
  const group = prefix => ansiOrder.map(k => `    ${k}: '${hash(s.ansi[prefix + k])}'`).join('\n');
  files.set(`generated/terminal/ejmlabs-${name}.warp.yaml`, `${banner('#')}
name: ejmlabs ${name}
accent: '${hash(s.accent)}'
background: '${hash(s.bg)}'
foreground: '${hash(s.fg)}'
details: ${name === 'dark' ? 'darker' : 'lighter'}
terminal_colors:
  normal:
${group('')}
  bright:
${group('bright-')}
`);
  const comp = (hex, i) => (rgb(hex)[i] / 255).toFixed(6);
  const color = (key, hex) => `\t<key>${key}</key>\n\t<dict>\n\t\t<key>Alpha Component</key>\n\t\t<real>1</real>\n\t\t<key>Blue Component</key>\n\t\t<real>${comp(hex, 2)}</real>\n\t\t<key>Color Space</key>\n\t\t<string>sRGB</string>\n\t\t<key>Green Component</key>\n\t\t<real>${comp(hex, 1)}</real>\n\t\t<key>Red Component</key>\n\t\t<real>${comp(hex, 0)}</real>\n\t</dict>`;
  const entries = [...list.map((v, i) => color(`Ansi ${i} Color`, v)), color('Background Color', s.bg), color('Foreground Color', s.fg), color('Bold Color', resolved[name].roles['text-strong']), color('Cursor Color', s.cursor), color('Cursor Text Color', s.cursorText), color('Selection Color', s.selBg), color('Selected Text Color', s.selFg), color('Link Color', s.accent)];
  files.set(`generated/terminal/ejmlabs-${name}.itermcolors`, `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<!-- ${banner('').trim()} -->\n<plist version="1.0">\n<dict>\n${entries.join('\n')}\n</dict>\n</plist>\n`);
}
const wt = name => {
  const s = termRoles(name);
  return { name: `ejmlabs ${name}`, background: hash(s.bg), foreground: hash(s.fg), cursorColor: hash(s.cursor), selectionBackground: hash(s.selBg), ...Object.fromEntries(ansiOrder.map(k => [wtKey(k), hash(s.ansi[k])])), ...Object.fromEntries(ansiOrder.map(k => [`bright${wtKey(k)[0].toUpperCase()}${wtKey(k).slice(1)}`, hash(s.ansi[`bright-${k}`])])) };
};
files.set('generated/terminal/ejmlabs.windows-terminal.json', `${JSON.stringify({ schemes: [wt('dark'), wt('light')] }, null, 2)}\n`);

const bands = resolveBands(theme, brand, resolved);
files.set('generated/tailwind.css', tailwindCss({ theme, brand, resolved, bands, banner: banner('').trim() }));
files.set('generated/window.css', windowCss({ resolved, banner: banner('').trim() }));

// 3. Write or verify.
let stale = 0;
for (const [path, content] of files) {
  const target = join(root, path);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) { console.error(`stale: packages/tokens/${path}`); stale++; }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
if (check && stale) process.exit(1);
console.log(check ? `tokens are current (${files.size} generated files, contrast ok)` : `wrote ${files.size} files under packages/tokens`);
