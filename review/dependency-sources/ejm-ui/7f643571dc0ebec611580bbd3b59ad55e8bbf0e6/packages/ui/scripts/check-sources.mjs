#!/usr/bin/env node
/**
 * styles.css scans the components most sites use; the docs, app, static and terminal styles add their opt-in folders. This checks the
 * contract that makes the split safe:
 *  1. Every utility class a folder's components use is generated when the entry that covers the folder is imported (the scan
 *     covers the folder, and the class is one Tailwind can build).
 *  2. A default folder never imports from an opt-in folder, because its classes would be missing from a default build.
 *  3. The default entry does not scan docs, app, static or terminal (nor any test file), which is the saving.
 * It prints the CSS size of each entry (gzip). Usage: node packages/ui/scripts/check-sources.mjs   (exit 1 on a failure)
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';

const src = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const require = createRequire(import.meta.url);
const { compile } = await import(pathToFileURL(require.resolve('@tailwindcss/node')).href);
const { Scanner } = require('@tailwindcss/oxide');

const ENTRIES = {
  default: ['styles.css'],
  docs: ['styles.css', 'styles-docs.css'],
  app: ['styles.css', 'styles-app.css'],
  static: ['styles.css', 'styles-static.css'],
  terminal: ['styles.css', 'styles-terminal.css'],
  all: ['styles.css', 'styles-docs.css', 'styles-app.css', 'styles-static.css', 'styles-terminal.css'],
  site: ['styles-site.css'],
  'site-docs': ['styles-site.css', 'styles-docs.css'],
};
const FOLDERS = { components: 'default', layout: 'default', shell: 'default', hooks: 'default', motion: 'default', docs: 'docs', app: 'app', static: 'static', terminal: 'terminal' };

const compileEntry = name => compile(ENTRIES[name].map(f => `@import "./${f}";`).join('\n'), { base: src, onDependency: () => {} });
const walk = d => readdirSync(d).flatMap(n => (statSync(join(d, n)).isDirectory() ? walk(join(d, n)) : [join(d, n)]));
const isSource = f => /\.(tsx?|jsx?)$/.test(f) && !/\.test\.|test-setup/.test(f);
const scanFiles = files => new Scanner({}).scanFiles(files.map(file => ({ content: readFileSync(file, 'utf8'), extension: extname(file).slice(1) })));
const scanEntry = c => new Scanner({ sources: c.sources }).scan();

const compilers = Object.fromEntries(await Promise.all(Object.keys(ENTRIES).map(async n => [n, await compileEntry(n)])));
// build() is cumulative, so a candidate is a real utility when adding it changes the CSS. A fresh compiler per call keeps earlier folders out.
const validOf = async candidates => {
  const compiler = await compileEntry('all');
  let last = compiler.build([]);
  return candidates.filter(c => {
    const css = compiler.build([c]);
    const grew = css !== last;
    last = css;
    return grew;
  });
};

const problems = [];
const scanned = Object.fromEntries(Object.keys(ENTRIES).map(n => [n, new Set(scanEntry(compilers[n]))]));
const own = {};
for (const [folder, entry] of Object.entries(FOLDERS)) {
  const files = walk(join(src, folder)).filter(isSource);
  own[folder] = new Set(await validOf(scanFiles(files)));
  const missing = [...own[folder]].filter(c => !scanned[entry].has(c));
  if (missing.length) problems.push(`${folder}/: ${missing.length} class(es) not generated by the ${entry} entry: ${missing.slice(0, 6).join(' ')}`);
  if (entry === 'default') {
    for (const f of files) {
      const bad = [...readFileSync(f, 'utf8').matchAll(/from\s+['"](\.\.\/(?:docs|app|static|terminal)(?:\/[^'"]*)?)['"]/g)];
      if (bad.length) problems.push(`${relative(src, f)} imports ${bad[0][1]}: a default folder cannot depend on an opt-in one`);
    }
  }
}
// React and native HTML share these recipes. Every profile that renders controls must scan them.
const controls = await validOf(scanFiles([join(src, 'control-recipes.mjs')]));
for (const entry of ['default', 'site']) {
  const missing = controls.filter(candidate => !scanned[entry].has(candidate));
  if (missing.length) problems.push(`${entry} entry misses shared control recipes: ${missing.slice(0, 6).join(' ')}`);
}
// The default entry must not read the opt-in folders (a stray word such as "contents" can appear in both, so look at files, not classes).
const filesOf = n => new Scanner({ sources: compilers[n].sources }).files.map(f => relative(src, f).split('\\').join('/'));
for (const f of ['docs', 'app', 'static', 'terminal']) {
  if (filesOf('default').some(p => p.startsWith(`${f}/`))) problems.push(`styles.css scans ${f}/: it must stay opt-in`);
  if (!filesOf(f).some(p => p.startsWith(`${f}/`))) problems.push(`the ${f} entry does not scan ${f}/`);
  if (filesOf(f).some(p => /\.test\./.test(p))) problems.push(`the ${f} entry scans test files`);
}
if (filesOf('default').some(p => /\.test\./.test(p))) problems.push('styles.css scans test files');
for (const f of ['app', 'docs']) if (filesOf('site').some(p => p.startsWith(`${f}/`))) problems.push(`styles-site.css scans ${f}/: it must stay opt-in`);
// Application composition is public through layout/, but marketing must not pay for game and form recipes.
for (const f of ['layout/Application.tsx', 'layout/ApplicationGame.tsx']) {
  if (filesOf('site').includes(f)) problems.push(`styles-site.css scans ${f}: application recipes must stay outside the marketing profile`);
}
const missingSiteDocs = [...own.docs].filter(c => !scanned['site-docs'].has(c));
if (missingSiteDocs.length) problems.push(`styles-site.css + styles-docs.css miss docs classes: ${missingSiteDocs.slice(0, 6).join(' ')}`);

const size = n => gzipSync(compilers[n].build([...scanned[n]]), { level: 9 }).length;
console.log('CSS gzip by entry: ' + Object.keys(ENTRIES).map(n => `${n} ${(size(n) / 1024).toFixed(1)} KB`).join(', '));
if (problems.length) {
  console.error(problems.map(p => `check-sources: ${p}`).join('\n'));
  process.exit(1);
}
console.log('check-sources ok: every folder gets its classes from its entry; docs, app, static and terminal stay out of the default entry');
